#!/usr/bin/env bash
# profile.sh: gprof flat profile of the serial training step (ROADMAP P7.2).
# Dev-time only: builds MODE=profile (release flags + -pg) and runs the W-A
# workload (small preset, B=32, T=256) shortened to 13 steps through
# bin/profile-float/bench, then writes gprof's flat profile with a header.
#
#   scripts/profile.sh [out.txt]        default: docs/profile/serial_W-A_gprof.txt
#
# Environment: DATA (default data/train.bin), STEPS (default 13).
# gprof samples only code compiled with -pg: time inside libm/libc (exp,
# tanh, memset, fread) is not attributed to any function, so percentages are
# of the sampled time in our own code.
set -euo pipefail
OUT=${1:-docs/profile/serial_W-A_gprof.txt}
DATA=${DATA:-data/train.bin}
STEPS=${STEPS:-13}
WORK=build/profile-cpu-serial-float/gprof
make MODE=profile bin/profile-float/bench > /dev/null
mkdir -p "$WORK" "$(dirname "$OUT")"
find "$WORK" -name 'gmon.*' -delete
CMD=(bin/profile-float/bench --config configs/small.cfg --max_steps "$STEPS" --batch_size 32
     --train_data "$DATA" --out "$WORK/bench.csv")
GMON_OUT_PREFIX="$WORK/gmon" "${CMD[@]}" > "$WORK/bench.log" 2>&1
GMON=$(ls "$WORK"/gmon.* | head -1)
{
  echo "# tslm serial gprof flat profile (ROADMAP P7.2), generated by scripts/profile.sh"
  echo "# command: GMON_OUT_PREFIX=... ${CMD[*]}"
  echo "# git: $(git rev-parse --short=12 HEAD 2>/dev/null || echo unknown)$(git diff --quiet HEAD -- 2>/dev/null || echo -dirty)"
  echo "# cpu: $(grep -m1 'model name' /proc/cpuinfo 2>/dev/null | cut -d: -f2- | sed 's/^ //' || echo unknown)"
  echo "# build: MODE=profile ($(${CXX:-g++} --version | head -1); -O3 -march=native -pg)"
  echo "# bench row of this run (timings include gprof overhead):"
  tail -1 "$WORK/bench.csv" | sed 's/^/#   /'
  echo "#"
  gprof -b -p bin/profile-float/bench "$GMON" | head -45
} > "$OUT"
echo "wrote $OUT"
